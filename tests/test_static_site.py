"""Real builder subprocesses and actual compiled assets in isolated synthetic roots."""
import hashlib
import json
import os
from pathlib import Path
import shutil
import stat
import subprocess
import sys
import tempfile
import unittest


ROOT = Path(__file__).resolve().parents[1]
NAMES = {'.nojekyll', 'index.html', 'app.js', 'model.js', 'styles.css', 'favicon.svg', 'demo.json'}


class StaticSiteTest(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory(prefix='impact static 合成 ')
        self.addCleanup(self.temporary.cleanup)
        self.directory = Path(self.temporary.name)
        self.root = self.directory / 'source tree 源'
        self.root.mkdir()
        shutil.copytree(ROOT / 'impact_ledger', self.root / 'impact_ledger', ignore=shutil.ignore_patterns('__pycache__'))
        (self.root / 'scripts').mkdir()
        shutil.copyfile(ROOT / 'scripts' / 'build_site.py', self.root / 'scripts' / 'build_site.py')
        self.target = self.root / 'site'

    def run_builder(self, *arguments, injection=None):
        script = self.root / 'scripts' / 'build_site.py'
        command = [sys.executable, str(script), *map(str, arguments)]
        if injection:
            command = [sys.executable, '-c', injection, str(script), *map(str, arguments)]
        return subprocess.run(command, cwd=self.directory, capture_output=True, text=True, timeout=15)

    def good_build(self, *arguments):
        result = self.run_builder(*arguments)
        self.assertEqual(result.returncode, 0, result.stderr + result.stdout)
        receipt = json.loads(result.stdout)
        self.assertTrue(receipt['valid'])
        self.assertEqual(receipt['operation'], 'build')
        self.assertEqual({item['name'] for item in receipt['files']}, NAMES)
        return receipt

    def rejected(self, result, code):
        self.assertEqual(result.returncode, 1, result.stderr + result.stdout)
        receipt = json.loads(result.stdout)
        self.assertFalse(receipt['valid'])
        self.assertIn(code, {error['code'] for error in receipt['errors']})
        self.assertLess(len(result.stdout), 2500)
        self.assertEqual(result.stderr, '')
        return receipt

    def state(self, directory=None):
        """Capture entry identity/bytes/mtime without following synthetic test links."""
        directory = directory or self.target
        info = directory.stat()
        result = {'.': (info.st_mode, info.st_ino, info.st_mtime_ns, None)}
        for path in directory.iterdir():
            info = path.lstat()
            content = path.read_bytes() if stat.S_ISREG(info.st_mode) else os.readlink(path) if path.is_symlink() else None
            result[path.name] = (info.st_mode, info.st_ino, info.st_mtime_ns, content)
        return result

    def test_existing_unknown_marker_is_refused_before_any_write(self):
        # Removing the inventory check would retain/upload the marker and rewrite allowed files.
        self.target.mkdir()
        (self.target / 'private-test-marker.txt').write_bytes(b'synthetic-private-value')
        (self.target / 'app.js').write_bytes(b'previous generated bytes')
        before = self.state()
        result = self.run_builder()
        self.assertNotEqual(result.returncode, 0, 'Old builder accepted an unlisted synthetic marker.')
        self.assertEqual(self.state(), before)
        self.rejected(result, 'unexpected_entry')
        self.assertNotIn('private-test-marker', result.stdout)
        self.assertNotIn('synthetic-private-value', result.stdout)

    def test_selected_directory_symlink_never_writes_unselected_directory(self):
        # Resolving the selected path before lstat would write through this link.
        other = self.directory / 'unselected 合成'
        other.mkdir()
        self.target.symlink_to(other, target_is_directory=True)
        before = self.state(other)
        result = self.run_builder()
        self.assertNotEqual(result.returncode, 0, 'Old builder followed the selected output symlink.')
        self.assertTrue(self.target.is_symlink())
        self.assertEqual(self.state(other), before)
        self.rejected(result, 'selected_symlink')

    def test_custom_output_has_exact_real_assets_and_seed_with_receipt(self):
        target = self.directory / 'published payload 目录'
        receipt = self.good_build('--output-directory', target)
        self.assertFalse(self.target.exists())
        self.assertEqual({path.name for path in target.iterdir()}, NAMES)
        source = self.root / 'impact_ledger' / 'static'
        for name in ['app.js', 'model.js', 'styles.css', 'favicon.svg']:
            self.assertEqual((target / name).read_bytes(), (source / name).read_bytes())
        self.assertEqual((target / 'index.html').read_bytes(), (source / 'index.html').read_bytes().replace(b'data-mode="local"', b'data-mode="static"'))
        self.assertEqual((target / '.nojekyll').read_bytes(), b'')
        demo = (target / 'demo.json').read_bytes()
        self.assertEqual(len(demo), 32929)
        self.assertEqual(hashlib.sha256(demo).hexdigest(), '3c8b6623aaef31146f4e196263fe3611f87336e72144506a882a011792069938')
        for item in receipt['files']:
            actual = (target / item['name']).read_bytes()
            self.assertEqual(item['bytes'], len(actual))
            self.assertEqual(item['sha256'], hashlib.sha256(actual).hexdigest())

    def test_repeated_build_repairs_only_allowed_regular_missing_or_changed_files(self):
        first = self.good_build()
        self.assertEqual(self.good_build(), first)
        (self.target / 'app.js').write_bytes(b'old version')
        (self.target / '.nojekyll').write_bytes(b'nonempty marker')
        (self.target / 'demo.json').unlink()
        self.assertEqual(self.good_build(), first)

    def test_known_filename_symlink_is_refused_without_following_it(self):
        self.good_build()
        outside = self.directory / 'unselected.txt'
        outside.write_bytes(b'keep synthetic original')
        (self.target / 'app.js').unlink()
        (self.target / 'app.js').symlink_to(outside)
        before = self.state()
        for arguments in [(), ('--verify-only',)]:
            self.rejected(self.run_builder(*arguments), 'nonregular_entry')
            self.assertEqual(self.state(), before)
            self.assertEqual(outside.read_bytes(), b'keep synthetic original')

    def test_atomic_replacement_detaches_hardlink_without_touching_original(self):
        self.good_build()
        outside = self.directory / 'unselected original.txt'
        outside.write_bytes(b'keep original bytes')
        before = (outside.read_bytes(), outside.stat().st_mtime_ns, outside.stat().st_ino)
        (self.target / 'app.js').unlink()
        os.link(outside, self.target / 'app.js')
        self.good_build()
        self.assertEqual((outside.read_bytes(), outside.stat().st_mtime_ns, outside.stat().st_ino), before)
        self.assertNotEqual((self.target / 'app.js').stat().st_ino, outside.stat().st_ino)

    def test_source_output_overlap_and_ancestor_alias_are_refused(self):
        source = self.root / 'impact_ledger' / 'static'
        alias = self.directory / 'ancestor alias'
        alias.symlink_to(self.root / 'impact_ledger', target_is_directory=True)
        before = self.state(source)
        for target in [source, source / 'nested output', alias / 'static']:
            with self.subTest(target=target):
                self.rejected(self.run_builder('--output-directory', target), 'source_overlap')
                self.assertEqual(self.state(source), before)

    def test_trusted_ancestor_alias_is_canonicalized_for_unrelated_output(self):
        parent = self.directory / 'trusted actual parent'
        parent.mkdir()
        alias = self.directory / 'trusted parent alias'
        alias.symlink_to(parent, target_is_directory=True)
        self.good_build('--output-directory', alias / 'payload')
        self.assertEqual({path.name for path in (parent / 'payload').iterdir()}, NAMES)

    def test_selected_file_or_dangling_symlink_is_refused(self):
        self.target.write_bytes(b'keep selected file')
        self.rejected(self.run_builder(), 'output_not_directory')
        self.assertEqual(self.target.read_bytes(), b'keep selected file')
        self.target.unlink()
        self.target.symlink_to(self.directory / 'missing')
        self.rejected(self.run_builder(), 'selected_symlink')
        self.assertTrue(self.target.is_symlink())
        self.assertFalse((self.directory / 'missing').exists())

    def test_directory_and_fifo_entries_are_refused_before_writes(self):
        for kind in ['directory', 'fifo']:
            with self.subTest(kind=kind):
                self.target.mkdir(exist_ok=True)
                path = self.target / 'app.js'
                path.mkdir() if kind == 'directory' else os.mkfifo(path)
                before = self.state()
                for arguments in [(), ('--verify-only',)]:
                    self.rejected(self.run_builder(*arguments), 'nonregular_entry')
                    self.assertEqual(self.state(), before)
                path.rmdir() if kind == 'directory' else path.unlink()

    def test_verification_is_exact_and_preserves_target_bytes_mtime_and_entries(self):
        build = self.good_build()
        before = self.state()
        directory_mtime = self.target.stat().st_mtime_ns
        result = self.run_builder('--verify-only')
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        receipt = json.loads(result.stdout)
        self.assertTrue(receipt['valid'])
        self.assertEqual(receipt['operation'], 'verify')
        self.assertEqual(receipt['files'], build['files'])
        self.assertEqual(self.state(), before)
        self.assertEqual(self.target.stat().st_mtime_ns, directory_mtime)

    def test_verifier_rejects_each_modified_payload_file_without_repair(self):
        self.good_build()
        for name in sorted(NAMES):
            with self.subTest(name=name):
                path = self.target / name
                original = path.read_bytes()
                if name == 'demo.json':
                    value = json.loads(original)
                    value['sessions'][0]['program'] = 'Changed synthetic program'
                    path.write_text(json.dumps(value), encoding='utf-8')
                else:
                    path.write_bytes(original + b'changed')
                before = self.state()
                receipt = self.rejected(self.run_builder('--verify-only'), 'content_mismatch')
                self.assertIn({'code': 'content_mismatch', 'file': name}, receipt['errors'])
                self.assertEqual(self.state(), before)
                path.write_bytes(original)

    def test_verifier_refuses_missing_and_extra_entries_without_repair(self):
        self.good_build()
        (self.target / 'model.js').unlink()
        before = self.state()
        self.rejected(self.run_builder('--verify-only'), 'missing_file')
        self.assertEqual(self.state(), before)
        self.good_build()
        (self.target / 'unknown directory').mkdir()
        before = self.state()
        self.rejected(self.run_builder('--verify-only'), 'unexpected_entry')
        self.assertEqual(self.state(), before)

    def test_verifier_does_not_create_missing_output_or_parent(self):
        target = self.directory / 'absent parent' / 'absent output'
        self.rejected(self.run_builder('--verify-only', '--output-directory', target), 'missing_output')
        self.assertFalse(target.parent.exists())
        self.rejected(self.run_builder('--output-directory', target), 'io_error')
        self.assertFalse(target.parent.exists())

    def test_controlled_read_error_has_no_traceback_or_private_values(self):
        self.good_build()
        before = self.state()
        injection = '''import runpy, sys
from pathlib import Path
from unittest.mock import patch
script, *arguments = sys.argv[1:]
sys.argv = [script, *arguments]
original = Path.read_bytes
def denied(path):
    if path.name == 'app.js' and path.parent.name == 'site':
        raise PermissionError('synthetic-private-io-value')
    return original(path)
with patch.object(Path, 'read_bytes', denied):
    runpy.run_path(script, run_name='__main__')
'''
        result = self.run_builder('--verify-only', injection=injection)
        self.rejected(result, 'io_error')
        self.assertNotIn('synthetic-private-io-value', result.stdout)
        self.assertEqual(self.state(), before)

    def test_failed_staging_write_cleans_partial_temporary_without_changing_generated_files(self):
        self.good_build()
        before = self.state()
        injection = '''import runpy, sys, tempfile
from contextlib import contextmanager
from unittest.mock import patch
script, *arguments = sys.argv[1:]
sys.argv = [script, *arguments]
original = tempfile.NamedTemporaryFile
@contextmanager
def partial_write(*arguments, **keywords):
    with original(*arguments, **keywords) as stream:
        class BrokenWrite:
            name = stream.name
            def write(self, body):
                stream.write(body[:5])
                raise OSError('synthetic-private-staging-value')
        yield BrokenWrite()
with patch.object(tempfile, 'NamedTemporaryFile', partial_write):
    runpy.run_path(script, run_name='__main__')
'''
        result = self.run_builder(injection=injection)
        self.rejected(result, 'io_error')
        self.assertNotIn('synthetic-private-staging-value', result.stdout)
        after = self.state()
        del before['.'], after['.']  # Owned create/unlink operations can change directory mtime.
        self.assertEqual(after, before)

    def test_failed_replace_cleans_owned_temporaries_and_preserves_unrelated_file(self):
        self.good_build()
        outside = self.directory / 'unrelated.txt'
        outside.write_bytes(b'keep unrelated bytes')
        injection = '''import os, runpy, sys
from unittest.mock import patch
script, *arguments = sys.argv[1:]
sys.argv = [script, *arguments]
original = os.replace
calls = 0
def fail_second(source, destination):
    global calls
    calls += 1
    if calls == 2:
        raise OSError('synthetic-private-write-value')
    return original(source, destination)
with patch.object(os, 'replace', fail_second):
    runpy.run_path(script, run_name='__main__')
'''
        result = self.run_builder(injection=injection)
        self.rejected(result, 'io_error')
        self.assertNotIn('synthetic-private-write-value', result.stdout)
        self.assertEqual({path.name for path in self.target.iterdir()}, NAMES)
        self.assertEqual(outside.read_bytes(), b'keep unrelated bytes')
        self.good_build()


if __name__ == '__main__':
    unittest.main()
